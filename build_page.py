"""Generate the public numeric payload from saved rankings and backtest results.
No database access; no raw historical prices are published.
"""
import argparse
import json
from pathlib import Path
import pandas as pd
from paths import ROOT


def build(results,output):
    result=Path(results)
    orders=pd.read_csv(result/'picks.csv');rank=pd.read_csv(result/'picks.ranking.csv')
    annual=pd.read_csv(result/'seg_years.csv')
    annual=annual[(annual.min_to==300000)&(annual.basket=='płynność 21–140 (proxy)')]
    descriptions=json.loads((ROOT/'data/company_descriptions.json').read_text())
    codes=orders.ticker.unique();px={};signals={};companies={};strategies={};stats={}
    for tk in codes:
        row=rank[rank.ticker==tk].iloc[0]
        px[tk]=round(float(row.close),4)
        signals[tk]=[float(row.hi52),float(row.mom3),float(row.med_turnover_63)/1e6]
        companies[tk]=descriptions.get(tk,[tk,''])
    mapping={'podium':'podium (combo, 3)','spokojna':'spokojna (hi52, 10)'}
    for strategy,variant in mapping.items():
        o=orders[orders.strategy==strategy]
        if set(o.action)-{'buy','reserve'}:raise ValueError('This public initial-buy page cannot render a portfolio review')
        strategies[strategy]=dict(n=3 if strategy=='podium' else 10,buy=o[o.role=='buy'].ticker.tolist(),res=o[o.role=='reserve'].ticker.tolist())
        g=annual[annual.strat==variant];x=g.ret
        if len(g)!=23:raise ValueError('Expected 23 annual windows')
        stats[strategy]=dict(mean=x.mean(),median=x.median(),losses=int((x<0).sum()),worst=x.min(),beat=int((x>g.wig).sum()))
    stats['wig']=dict(mean=annual.groupby('year').wig.first().mean())
    years={}
    for y,g in annual.groupby('year'):
        years[int(y)]=[float(g[g.strat==mapping[s]].ret.iloc[0]) for s in ['podium','spokojna']]+[float(g.wig.iloc[0])]
    summary=json.loads((result/'picks.json').read_text())
    payload=dict(companies=companies,prices=px,signals=signals,strategies=strategies,stats=stats,years=years,
        as_of=str(rank.signal_date.iloc[0]),trade_date=str(rank.trade_date.iloc[0]),summary=summary,
        model='raw-pln-integer-deferred-dividends-v2',auction_volume_verified=False)
    Path(output).write_text('// Generated by build_page.py; edit sources, not numbers.\nconst PAGE = '+json.dumps(payload,ensure_ascii=False,allow_nan=False,indent=2)+';\n')


if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--results',default=str(ROOT/'results'));ap.add_argument('--out',default=str(ROOT/'docs/results.js'))
    args=ap.parse_args();build(args.results,args.out)
